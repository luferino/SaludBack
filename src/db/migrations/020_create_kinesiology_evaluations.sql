-- Initial evaluations are editable drafts in this delivery. Submission snapshots,
-- consent evidence and review events are introduced by later feature units.
-- clinical_records remains the one longitudinal history per patient.
CREATE TABLE kinesiology_evaluations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinical_record_id BIGINT NOT NULL REFERENCES clinical_records(id) ON DELETE NO ACTION,
  patient_id UUID NOT NULL REFERENCES patients(id) ON DELETE NO ACTION,
  author_id UUID NOT NULL REFERENCES users(id) ON DELETE NO ACTION,
  origin_student_habilitation_id UUID NOT NULL REFERENCES student_academic_habilitations(id) ON DELETE NO ACTION,
  origin_subject_id UUID NOT NULL REFERENCES subjects(id) ON DELETE NO ACTION,
  origin_group_id UUID NOT NULL REFERENCES academic_groups(id) ON DELETE NO ACTION,
  content JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status = 'draft'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX kinesiology_evaluations_patient_id_idx ON kinesiology_evaluations(patient_id, id);
CREATE INDEX kinesiology_evaluations_author_id_idx ON kinesiology_evaluations(author_id, id);
