CREATE TABLE kinesiology_consent_attestations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id BIGINT NOT NULL REFERENCES kinesiology_evaluations(id) ON DELETE RESTRICT,
  paper_signature_date DATE NOT NULL,
  verified_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  teacher_habilitation_id UUID NOT NULL REFERENCES teacher_academic_habilitations(id) ON DELETE RESTRICT,
  verified_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX kinesiology_consent_attestations_latest_idx
  ON kinesiology_consent_attestations (evaluation_id, id DESC);
