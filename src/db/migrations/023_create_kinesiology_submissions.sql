ALTER TABLE kinesiology_evaluations
  DROP CONSTRAINT kinesiology_evaluations_status_check,
  ADD CONSTRAINT kinesiology_evaluations_status_check CHECK (status IN ('draft', 'submitted'));

CREATE TABLE kinesiology_evaluation_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id BIGINT NOT NULL REFERENCES kinesiology_evaluations(id) ON DELETE RESTRICT,
  ordinal BIGINT NOT NULL CHECK (ordinal > 0),
  submitted_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  clinical_content JSONB NOT NULL,
  patient_snapshot JSONB NOT NULL,
  age_at_admission INTEGER,
  verified_consent_snapshot JSONB NOT NULL,
  UNIQUE (evaluation_id, ordinal)
);

CREATE INDEX kinesiology_evaluation_submissions_latest_idx
  ON kinesiology_evaluation_submissions (evaluation_id, ordinal DESC);

CREATE TABLE kinesiology_evaluation_submission_studies (
  submission_id BIGINT NOT NULL REFERENCES kinesiology_evaluation_submissions(id) ON DELETE RESTRICT,
  ordinal INTEGER NOT NULL CHECK (ordinal >= 0),
  study_type TEXT NOT NULL CHECK (length(btrim(study_type)) > 0),
  description TEXT NOT NULL CHECK (length(btrim(description)) > 0),
  study_date DATE,
  PRIMARY KEY (submission_id, ordinal)
);
