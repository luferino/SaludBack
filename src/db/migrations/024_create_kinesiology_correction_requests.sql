ALTER TABLE kinesiology_evaluations
  ADD COLUMN correction_from_submission_id BIGINT
    REFERENCES kinesiology_evaluation_submissions(id) ON DELETE RESTRICT;

CREATE TABLE kinesiology_evaluation_correction_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id BIGINT NOT NULL REFERENCES kinesiology_evaluations(id) ON DELETE RESTRICT,
  submission_id BIGINT NOT NULL REFERENCES kinesiology_evaluation_submissions(id) ON DELETE RESTRICT,
  reason TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
  reviewed_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (evaluation_id, submission_id)
);

CREATE INDEX kinesiology_evaluation_correction_requests_history_idx
  ON kinesiology_evaluation_correction_requests (evaluation_id, id);
