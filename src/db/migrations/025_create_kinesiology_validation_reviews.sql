ALTER TABLE kinesiology_evaluations
  DROP CONSTRAINT kinesiology_evaluations_status_check,
  ADD CONSTRAINT kinesiology_evaluations_status_check
    CHECK (status IN ('draft', 'submitted', 'validated'));

ALTER TABLE kinesiology_evaluation_submissions
  ADD CONSTRAINT kinesiology_evaluation_submissions_evaluation_id_id_key
    UNIQUE (evaluation_id, id);

CREATE TABLE kinesiology_evaluation_validation_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evaluation_id BIGINT NOT NULL,
  submission_id BIGINT NOT NULL,
  reviewed_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  teacher_habilitation_id UUID NOT NULL REFERENCES teacher_academic_habilitations(id) ON DELETE RESTRICT,
  reviewed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT kinesiology_validation_reviews_submission_fk
    FOREIGN KEY (evaluation_id, submission_id)
    REFERENCES kinesiology_evaluation_submissions(evaluation_id, id) ON DELETE RESTRICT,
  UNIQUE (evaluation_id, submission_id)
);

CREATE INDEX kinesiology_evaluation_validation_reviews_history_idx
  ON kinesiology_evaluation_validation_reviews (evaluation_id, id);
