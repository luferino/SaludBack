ALTER TABLE kinesiology_evaluations
  ADD CONSTRAINT kinesiology_evaluations_id_patient_origin_unique
    UNIQUE (id, patient_id, origin_subject_id, origin_group_id);

CREATE TABLE kinesiology_evaluation_amendment_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  original_evaluation_id BIGINT NOT NULL,
  amendment_evaluation_id BIGINT NOT NULL UNIQUE,
  patient_id UUID NOT NULL,
  origin_subject_id UUID NOT NULL,
  origin_group_id UUID NOT NULL,
  created_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT kinesiology_evaluation_amendments_distinct_evaluations
    CHECK (original_evaluation_id <> amendment_evaluation_id),
  CONSTRAINT kinesiology_evaluation_amendments_original_fk
    FOREIGN KEY (original_evaluation_id, patient_id, origin_subject_id, origin_group_id)
    REFERENCES kinesiology_evaluations(id, patient_id, origin_subject_id, origin_group_id) ON DELETE RESTRICT,
  CONSTRAINT kinesiology_evaluation_amendments_child_fk
    FOREIGN KEY (amendment_evaluation_id, patient_id, origin_subject_id, origin_group_id)
    REFERENCES kinesiology_evaluations(id, patient_id, origin_subject_id, origin_group_id) ON DELETE RESTRICT
);

CREATE INDEX kinesiology_evaluation_amendment_original_idx
  ON kinesiology_evaluation_amendment_links (original_evaluation_id, id);
