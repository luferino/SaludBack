-- Separate, independently authored session drafts linked to a validated evaluation.
CREATE UNIQUE INDEX clinical_records_id_patient_unique ON clinical_records(id, patient_id);
CREATE UNIQUE INDEX kinesiology_evaluations_id_record_patient_unique
  ON kinesiology_evaluations(id, clinical_record_id, patient_id);
CREATE TABLE kinesiology_evolutions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  clinical_record_id BIGINT NOT NULL,
  patient_id UUID NOT NULL,
  evaluation_id BIGINT NOT NULL,
  author_id UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  origin_student_habilitation_id UUID NOT NULL REFERENCES student_academic_habilitations(id) ON DELETE RESTRICT,
  origin_subject_id UUID NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
  origin_group_id UUID NOT NULL REFERENCES academic_groups(id) ON DELETE RESTRICT,
  content JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status = 'draft'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  FOREIGN KEY (clinical_record_id, patient_id) REFERENCES clinical_records(id, patient_id) ON DELETE RESTRICT,
  FOREIGN KEY (evaluation_id, clinical_record_id, patient_id)
    REFERENCES kinesiology_evaluations(id, clinical_record_id, patient_id) ON DELETE RESTRICT
);
CREATE INDEX kinesiology_evolutions_patient_id_idx ON kinesiology_evolutions(patient_id, id);
CREATE INDEX kinesiology_evolutions_author_id_idx ON kinesiology_evolutions(author_id, id);
CREATE INDEX kinesiology_evolutions_evaluation_id_idx ON kinesiology_evolutions(evaluation_id, id);
