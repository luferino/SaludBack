-- Immutable clinical snapshots and origin-context review events for session evolutions.
ALTER TABLE kinesiology_evolutions DROP CONSTRAINT kinesiology_evolutions_status_check;
ALTER TABLE kinesiology_evolutions ADD CONSTRAINT kinesiology_evolutions_status_check
  CHECK (status IN ('draft', 'submitted', 'validated'));

CREATE TABLE kinesiology_evolution_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evolution_id BIGINT NOT NULL REFERENCES kinesiology_evolutions(id) ON DELETE RESTRICT,
  ordinal INTEGER NOT NULL CHECK (ordinal > 0),
  submitted_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  clinical_content JSONB NOT NULL,
  UNIQUE (evolution_id, ordinal),
  UNIQUE (id, evolution_id)
);
CREATE TABLE kinesiology_evolution_correction_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evolution_id BIGINT NOT NULL REFERENCES kinesiology_evolutions(id) ON DELETE RESTRICT,
  submission_id BIGINT NOT NULL,
  reason TEXT NOT NULL CHECK (length(btrim(reason)) > 0),
  reviewed_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (submission_id),
  FOREIGN KEY (submission_id, evolution_id)
    REFERENCES kinesiology_evolution_submissions(id, evolution_id) ON DELETE RESTRICT
);
CREATE TABLE kinesiology_evolution_validation_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evolution_id BIGINT NOT NULL REFERENCES kinesiology_evolutions(id) ON DELETE RESTRICT,
  submission_id BIGINT NOT NULL,
  reviewed_by UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  teacher_habilitation_id UUID NOT NULL REFERENCES teacher_academic_habilitations(id) ON DELETE RESTRICT,
  reviewed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (submission_id),
  FOREIGN KEY (submission_id, evolution_id)
    REFERENCES kinesiology_evolution_submissions(id, evolution_id) ON DELETE RESTRICT
);
CREATE INDEX kinesiology_evolution_submissions_history_idx ON kinesiology_evolution_submissions(evolution_id, ordinal DESC);
CREATE INDEX kinesiology_evolution_corrections_history_idx ON kinesiology_evolution_correction_requests(evolution_id, id);
CREATE INDEX kinesiology_evolution_reviews_history_idx ON kinesiology_evolution_validation_reviews(evolution_id, id);
